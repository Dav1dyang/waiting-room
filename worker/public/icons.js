/** One icon as an SVG string. Size is in CSS pixels; 11 keeps it at native scale. */
export function iconSvg(name, { size = 11, color = '#000000', cls = 'ic' } = {}) {
  const grid = ICONS[name];
  if (!grid) return '';
  let rects = '';
  const rows = grid.split('\n');
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    }
  }
  return `<svg class="${cls}" viewBox="0 0 11 11" width="${size}" height="${size}" fill="${color}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

/** Replace every <i data-icon="name"> inside root with its SVG. Idempotent. */
export function paintIcons(root = document) {
  for (const slot of root.querySelectorAll('[data-icon]')) {
    const name = slot.getAttribute('data-icon');
    const size = Number(slot.getAttribute('data-size') || 11);
    if (slot.getAttribute('data-painted') === name) continue;
    slot.innerHTML = iconSvg(name, { size });
    slot.setAttribute('data-painted', name);
  }
}
